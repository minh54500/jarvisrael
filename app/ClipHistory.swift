import AppKit

/// Historique du presse-papiers : les derniers textes et images copiés, à recopier d'un clic.
/// Gardé en mémoire seulement (rien sur le disque : on copie souvent des clés d'API), et les
/// copies marquées « secrètes » par les gestionnaires de mots de passe sont ignorées.
@MainActor
final class ClipHistory: ObservableObject {
    static let shared = ClipHistory()

    struct Clip: Identifiable, Equatable {
        let id = UUID()
        var text: String?
        var png: Data?        // l'image en PNG (compressée) : c'est elle qu'on recopie
        var image: NSImage?   // sa miniature, pour l'affichage
        var at = Date()
        static func == (a: Clip, b: Clip) -> Bool { a.id == b.id }
    }

    @Published private(set) var clips: [Clip] = []
    private var seen = NSPasteboard.general.changeCount
    private var timer: Timer?
    private static let limit = 30
    private static let imageLimit = 10  // une capture Retina pèse lourd : on en garde moins
    /// Types posés par les gestionnaires de mots de passe et les copies automatiques.
    private static let skipped: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                               "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    private init() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { _ in
            MainActor.assumeIsolated { ClipHistory.shared.poll() }
        }
        RunLoop.main.add(timer!, forMode: .common)
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != seen else { return }
        seen = pb.changeCount
        let types = pb.types ?? []
        if types.contains(where: { Self.skipped.contains($0.rawValue) }) || types.contains(.fileURL) { return }
        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            clips.removeAll { $0.text == s }
            clips.insert(Clip(text: String(s.prefix(100_000))), at: 0)
        } else if let raw = pb.data(forType: .png) ?? pb.data(forType: .tiff) {
            let isPNG = pb.data(forType: .png) != nil
            DispatchQueue.global(qos: .utility).async {  // conversion et miniature hors du fil principal
                guard let rep = NSBitmapImageRep(data: raw),
                      let png = isPNG ? raw : rep.representation(using: .png, properties: [:]),
                      let thumb = Self.thumbnail(rep) else { return }
                DispatchQueue.main.async {
                    MainActor.assumeIsolated { ClipHistory.shared.insert(Clip(png: png, image: thumb)) }
                }
            }
            return
        } else {
            return
        }
        trim()
    }

    private func insert(_ c: Clip) {
        clips.insert(c, at: 0)
        trim()
    }

    private func trim() {
        var images = 0
        clips = clips.filter { c in
            guard c.png != nil else { return true }
            images += 1
            return images <= Self.imageLimit
        }
        if clips.count > Self.limit { clips.removeLast(clips.count - Self.limit) }
    }

    /// Miniature d'au plus 240 px de large.
    nonisolated private static func thumbnail(_ rep: NSBitmapImageRep) -> NSImage? {
        let w = Double(rep.pixelsWide), h = Double(rep.pixelsHigh)
        guard w > 0, h > 0 else { return nil }
        let k = min(1, 240 / w), size = NSSize(width: (w * k).rounded(), height: (h * k).rounded())
        let img = NSImage(size: size)
        img.lockFocus()
        NSGraphicsContext.current?.imageInterpolation = .high
        rep.draw(in: NSRect(origin: .zero, size: size))
        img.unlockFocus()
        return img
    }

    /// Remet un élément dans le presse-papiers (et en tête de liste).
    func copy(_ c: Clip) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let t = c.text { pb.setString(t, forType: .string) } else if let png = c.png { pb.setData(png, forType: .png) }
        seen = pb.changeCount
        clips.removeAll { $0.id == c.id }
        var top = c
        top.at = Date()
        clips.insert(top, at: 0)
    }

    func remove(_ c: Clip) { clips.removeAll { $0.id == c.id } }
    func clear() { clips = [] }
}
